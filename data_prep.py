    one_hot_cols = one_hot_df.columns.tolist()
    num_cols = [c for c in df.columns if c not in cat_cols + ignore_cols + target_col + one_hot_source_cols]

    # Sort chronologically first
    order = np.argsort(df["date"].to_numpy())

    df["top3"] = (
        (df["pos_numeric"] >= 1) &
        (df["pos_numeric"] <= 3)
    ).astype(float)

    # Create feature sets
    X_cat = df[cat_cols].iloc[order].copy()
    X_num = df[num_cols].iloc[order].copy()
    X_one_hot = one_hot_df.iloc[order].copy()
    y = df[["top3"]].iloc[order].copy()

