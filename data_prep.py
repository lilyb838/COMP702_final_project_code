    train_end = int(n * 0.70)
    val_end = int(n * 0.90)

    # Train
    X_cat_train = X_cat.iloc[:train_end].copy()
    X_num_train = X_num.iloc[:train_end].copy()
    X_one_hot_train = X_one_hot.iloc[:train_end].copy()
    y_train = y.iloc[:train_end].copy()


