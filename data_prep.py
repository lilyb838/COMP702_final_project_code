#convert sp
def convert_sp(x):
    if pd.isna(x) or x == '':
        return None

    x = x.replace('F', '').replace('J', '').replace('C', '')

    if x == 'Evens' or x == "Evs":
        return 1.0

    if '/' in x:
        num, den = x.split('/')
        return float(num) / float(den)

    try:
        return float(x)
    except:
        return None


#convert distance to furlongs
def convert_dist(x):
  if pd.isna(x):
        return None

  x = str(x).strip()

  miles = re.search(r'(\d+)m', x)
  furlongs = re.search(r'(\d+(?:/\d+)?)f', x)

  total = 0

  if miles:
      total += int(miles.group(1)) * 8

  if furlongs:
      f = furlongs.group(1)
      if '/' in f:
          num, den = f.split('/')
          total += float(num) / float(den)
      else:
          total += float(f)

  return total

#cleaning names
def clean_horses_names(name):
    if pd.isna(name):
        return None

    name = re.sub(r'[()]', '', name)
    name = name.lower().strip()
    name = re.sub(r'\.', '', name)
    name = re.sub(r'\b(i)\b', '', name)
    name = re.sub(r'\s+', ' ', name).strip()

    return name

def clean_names(name):
  if pd.isna(name):
        return None

  name = name.lower().strip()
  name = re.sub(r"\b(mr|mrs|ms|miss|dr)\b", "", name)
  name = name.replace("'", "")
  name = re.sub(r"[^a-z\s]", " ", name)
  name = " ".join(name.split())

  return name

