    X_cat_val = X_cat.iloc[train_end:val_end].copy()
    X_num_val = X_num.iloc[train_end:val_end].copy()
    X_one_hot_val = X_one_hot.iloc[train_end:val_end].copy()
    y_val = y.iloc[train_end:val_end].copy()


