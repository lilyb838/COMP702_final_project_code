from sklearn.metrics import roc_auc_score, f1_score, confusion_matrix, average_precision_score, log_loss
import torch

def evaluate_model(model, test_loader, process_batch, device):

    model.eval()

    y_true = []
    y_scores = []

    with torch.no_grad():

        for batch in test_loader:

            batch, batch_y, batch_size = process_batch(
                batch,
                device
            )

            logits = model(batch)
            logits = logits[:batch_size]

            probabilities = torch.sigmoid(logits)

            y_true.extend(
                batch_y.view(-1).cpu().tolist()
            )

            y_scores.extend(
                probabilities.view(-1).cpu().tolist()
            )

    return {
        "roc_auc": roc_auc_score(y_true, y_scores),
        "auprc": average_precision_score(y_true, y_scores),
        "log_loss": log_loss(y_true, y_scores)
    }