import torch
from GNN_model import HorsePredictionGNN, process_gnn_batch
from train_validate_func import train_and_validate
from torch_geometric.loader import NeighborLoader
from torch.utils.data import DataLoader
import random
from data_prep import prepare_data, prepare_mlp_data, prepare_gnn_data
import numpy as np
from google.colab import drive
from sklearn.metrics import roc_auc_score
import matplotlib.pyplot as plt
import pandas as pd
from MLP_model import HorsePredictionMLP, process_mlp_batch
from evaluation_func import evaluate_model

df = pd.read_csv("raceform.csv")

# Reproducibility
random_seed = 42

random.seed(random_seed)
np.random.seed(random_seed)
torch.manual_seed(random_seed)
torch.cuda.manual_seed_all(random_seed)

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

df = prepare_data()

data, gnn_train_loader, gnn_val_loader, gnn_test_loader, train_indices, val_indices = prepare_gnn_data(df)

mlp_train_loader, mlp_val_loader, mlp_test_loader, cat_maps, train_dataset, val_dataset, test_dataset = prepare_mlp_data(df)

gnn_model_args = {
    "n_horse_features": data["horse"].x.shape[1],
    "n_race_features": data["race"].x.shape[1],
    "n_runner_features": data["runner"].x.shape[1],
    "n_jockey_features": data["jockey"].x.shape[1],
    "n_trainer_features": data["trainer"].x.shape[1],
    "n_owner_features": data["owner"].x.shape[1],
    "data": data
}

gnn_model = HorsePredictionGNN(
    **gnn_model_args,
    dropout=0.2
).to(device)

mlp_model_args = {
    "n_horse_id": len(cat_maps["horse_id"]) + 1,
    "n_dam_id": len(cat_maps["dam_id"]) + 1,
    "n_sire_id": len(cat_maps["sire_id"]) + 1,
    "n_damsire_id": len(cat_maps["damsire_id"]) + 1,
    "n_jockey_id": len(cat_maps["jockey_id"]) + 1,
    "n_trainer_id": len(cat_maps["trainer_id"]) + 1,
    "n_owner_id": len(cat_maps["owner_id"]) + 1,
    "n_course": len(cat_maps["course"]) + 1,
    "num_features": train_dataset.X_num.shape[1],
    "output_size": train_dataset.y.shape[1]
}
mlp_model = HorsePredictionMLP(
    **mlp_model_args
).to(device)

#paths must already be saved to folder
gnn_checkpoint = torch.load(
    "best_gnn.pth",
    map_location=device,
    weights_only=False
)

gnn_model.load_state_dict(
    gnn_checkpoint["gnn_model_state_dict"]
)

mlp_checkpoint = torch.load(
    "best_mlp.pth",
    map_location=device,
    weights_only=False
)

mlp_model.load_state_dict(
    mlp_checkpoint["mlp_model_state_dict"]
)

from torch.utils.data import Subset, DataLoader
order = np.argsort(df["date"].to_numpy())

test_indices = order[int(len(df) * 0.9):]

test_df = df.iloc[test_indices]

horse_counts = test_df["horse_id"].value_counts()
jockey_counts = test_df["jockey_id"].value_counts()

rows_both_once_indices = np.where(
    (test_df["horse_id"].map(horse_counts) == 1) &
    (test_df["jockey_id"].map(jockey_counts) == 1)
)[0]

subset_dataset = Subset(test_dataset, rows_both_once_indices)

subset_loader = DataLoader(
    subset_dataset,
    batch_size=1024,
    shuffle=False
)
mlp_results_both_once = evaluate_model(
    mlp_model,
    subset_loader,
    process_mlp_batch,
    device
)
print(mlp_results_both_once)

subset_indices = torch.tensor(
    test_indices[rows_both_once_indices],
    dtype=torch.long
)

subset_loader = NeighborLoader(
    data,
    input_nodes=("runner", subset_indices),
    num_neighbors=[15, 15],
    batch_size=512,
    shuffle=False
)

gnn_results_both_once = evaluate_model(
    gnn_model,
    subset_loader,
    process_gnn_batch,
    device
)

print(gnn_results_both_once)