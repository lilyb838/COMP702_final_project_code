def split_gender_row(row):

    left_names = list(dict.fromkeys(
        x.strip() for x in row["base_name"].split(", ")
    ))

    right_names = list(dict.fromkeys(
        x.strip() for x in row["candidates"].split(", ")
    ))


    # -----------------------------
    # Group left names
    # -----------------------------

    left_groups = {
        "male": [],
        "female": [],
        "neutral": []
    }

    for name in left_names:
        left_groups[get_gender(name)].append(name)

    left_groups = {
        k: v for k, v in left_groups.items()
        if v
    }


    # -----------------------------
    # Group candidates
    # -----------------------------

    candidate_groups = {
        "male": [],
        "female": [],
        "neutral": []
    }

    for name in right_names:
        candidate_groups[get_gender(name)].append(name)


    output = []


    # ==================================================
    # CASE 1:
    # Left side already has gendered names
    # ==================================================

    left_has_gender = any(
        g in left_groups
        for g in ["male", "female"]
    )


    if left_has_gender:

        # Split existing left genders
        for gender in ["male", "female"]:

            if gender in left_groups:

                keep = (
                    candidate_groups[gender]
                    + candidate_groups["neutral"]
                )

                output.append({
                    "base_name": ", ".join(left_groups[gender]),
                    "n_candidates": len(set(keep)),
                    "candidates": ", ".join(sorted(set(keep)))
                })


        # ------------------------------------------------
        # Add missing conflicting gender candidates
        # ONLY when left side is already gendered
        # ------------------------------------------------

        represented_left = set(left_groups.keys())


        for gender in ["male", "female"]:

            if (
                gender not in represented_left
                and candidate_groups[gender]
            ):

                keep = (
                    candidate_groups[gender]
                    + candidate_groups["neutral"]
                )

                output.append({
                    "base_name": ", ".join(candidate_groups[gender]),
                    "n_candidates": len(set(keep)),
                    "candidates": ", ".join(sorted(set(keep)))
                })



    # ==================================================
    # CASE 2:
    # Left side is neutral
    # ==================================================

    else:

        # Only split neutral names when BOTH genders exist
        if (
            candidate_groups["male"]
            and candidate_groups["female"]
        ):

            for gender in ["male", "female"]:

                keep = (
                    candidate_groups[gender]
                    + candidate_groups["neutral"]
                )

                output.append({
                    "base_name": ", ".join(left_names),
                    "n_candidates": len(set(keep)),
                    "candidates": ", ".join(sorted(set(keep)))
                })

        else:

            output.append({
                "base_name": ", ".join(left_names),
                "n_candidates": len(set(right_names)),
                "candidates": ", ".join(sorted(set(right_names)))
            })


    return output



