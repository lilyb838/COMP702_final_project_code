def candidate_group_conflict(candidates):

    titles = {"mr", "mrs", "ms", "miss"}


    cleaned = []

    for name in candidates:

        parts = [
            x.lower()
            for x in name.split()
            if x.lower() not in titles
        ]

        cleaned.append(parts)



    # compare all candidate pairs

    for i in range(len(cleaned)):

        for j in range(i + 1, len(cleaned)):

            a = cleaned[i]
            b = cleaned[j]


            # surname conflict
            if a[-1] != b[-1]:
                return True


            first_a = a[0]
            first_b = b[0]


            # Two full first names differ
            if len(first_a) > 1 and len(first_b) > 1:

                if first_a != first_b:
                    return True



            # Middle name comparison

            middle_a = a[1:-1]
            middle_b = b[1:-1]


            if middle_a and middle_b:

                # different number of middle names
                if len(middle_a) != len(middle_b):
                    return True


                for x, y in zip(middle_a, middle_b):

                    # both full
                    if len(x) > 1 and len(y) > 1:

                        if x != y:
                            return True


                    # one initial, one full
                    elif len(x) == 1 and len(y) > 1:

                        if x != y[0]:
                            return True


                    elif len(y) == 1 and len(x) > 1:

                        if y != x[0]:
                            return True


    return False



