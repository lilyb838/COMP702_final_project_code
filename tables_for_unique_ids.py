for names in groups.values():

    for i in range(len(names)):
        for j in range(i + 1, len(names)):

            horse1 = names[i]
            horse2 = names[j]

            # 1. Length difference
            if abs(len(horse1) - len(horse2)) > 3:
                continue

            # 2. Country suffix
            if horse1.split()[-1] != horse2.split()[-1]:
                continue

            # 3. Sex check
            sex1 = sex_lookup.get(horse1)
            sex2 = sex_lookup.get(horse2)

            if pd.isna(sex1) or pd.isna(sex2):
                continue

            if sex1 != sex2:
                continue

            # 4. Current racing age check
            age1 = age_lookup.get(horse1)
            age2 = age_lookup.get(horse2)

            if pd.isna(age1) or pd.isna(age2):
                continue

            # Extract country suffixes
            code1 = names[i].split()[-1].lower()
            code2 = names[j].split()[-1].lower()

            # If both horses use Northern Hemisphere rules, ages must match exactly
            if code1 in northern_codes and code2 in northern_codes:
                if age1 != age2:
                    continue

            # Otherwise (South American or other Southern Hemisphere), allow a 1-year difference
            else:
                if abs(age1 - age2) > 1:
                    continue

            # 5. Skip if both names appear in the same race
            if race_ids_lookup[horse1].intersection(race_ids_lookup[horse2]):
                continue

            # 6. Parents exist
            dam1 = dam_lookup.get(horse1)
            dam2 = dam_lookup.get(horse2)

